-- be nice
SET role_before_drop = CURRENT_ROLE();

USE ROLE SYSADMIN;
EXECUTE IMMEDIATE $$
DECLARE
    schema_exists INTEGER;
BEGIN
    -- Check schema exists first
    SELECT COUNT(*) INTO :schema_exists FROM {{in_sf_env}}_GROUP_RAW.information_schema.schemata WHERE upper(schema_name) = upper('{{in_sf_env}}_SALESFORCE');
    IF (schema_exists > 0) THEN
        USE ROLE SECURITYADMIN;

        REVOKE OWNERSHIP ON FUTURE EXTERNAL TABLES IN SCHEMA {{in_sf_env}}_GROUP_RAW.{{in_sf_env}}_SALESFORCE FROM SYSADMIN;
        REVOKE OWNERSHIP ON FUTURE FILE FORMATS IN SCHEMA {{in_sf_env}}_GROUP_RAW.{{in_sf_env}}_SALESFORCE FROM SYSADMIN;
        REVOKE OWNERSHIP ON FUTURE FUNCTIONS IN SCHEMA {{in_sf_env}}_GROUP_RAW.{{in_sf_env}}_SALESFORCE FROM SYSADMIN;
        REVOKE OWNERSHIP ON FUTURE MATERIALIZED VIEWS IN SCHEMA {{in_sf_env}}_GROUP_RAW.{{in_sf_env}}_SALESFORCE FROM SYSADMIN;
        REVOKE OWNERSHIP ON FUTURE PROCEDURES IN SCHEMA {{in_sf_env}}_GROUP_RAW.{{in_sf_env}}_SALESFORCE FROM SYSADMIN;
        REVOKE OWNERSHIP ON FUTURE SEQUENCES IN SCHEMA {{in_sf_env}}_GROUP_RAW.{{in_sf_env}}_SALESFORCE FROM SYSADMIN;
        REVOKE OWNERSHIP ON FUTURE STAGES IN SCHEMA {{in_sf_env}}_GROUP_RAW.{{in_sf_env}}_SALESFORCE FROM SYSADMIN;
        REVOKE OWNERSHIP ON FUTURE STREAMS IN SCHEMA {{in_sf_env}}_GROUP_RAW.{{in_sf_env}}_SALESFORCE FROM SYSADMIN;
        REVOKE OWNERSHIP ON FUTURE TABLES IN SCHEMA {{in_sf_env}}_GROUP_RAW.{{in_sf_env}}_SALESFORCE FROM SYSADMIN;
        REVOKE OWNERSHIP ON FUTURE TASKS IN SCHEMA {{in_sf_env}}_GROUP_RAW.{{in_sf_env}}_SALESFORCE FROM SYSADMIN;
        REVOKE OWNERSHIP ON FUTURE VIEWS IN SCHEMA {{in_sf_env}}_GROUP_RAW.{{in_sf_env}}_SALESFORCE FROM SYSADMIN;

        GRANT OWNERSHIP ON SCHEMA {{in_sf_env}}_GROUP_RAW.{{in_sf_env}}_SALESFORCE TO ROLE SYSADMIN REVOKE CURRENT GRANTS;
    END IF;
    RETURN 'SUCCESS';
END;
$$;

USE ROLE SYSADMIN;
DROP SCHEMA IF EXISTS {{in_sf_env}}_GROUP_RAW.{{in_sf_env}}_SALESFORCE CASCADE;

-- return to the caller's role
USE ROLE IDENTIFIER($role_before_drop);
UNSET role_before_drop;
