    STAGE_NAME VARCHAR(758) NOT NULL,
    TABLE_NAME VARCHAR(256) NOT NULL,
    STAGE_FILE_NAME VARCHAR(1024) NOT NULL,
    IS_ALERT_SENT BOOLEAN DEFAULT FALSE,
    CREATED_TIMESTAMP TIMESTAMP_TZ(9) DEFAULT CURRENT_TIMESTAMP,
    primary key (STAGE_NAME, STAGE_FILE_NAME)
);
